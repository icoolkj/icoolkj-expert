def render(name: str) -> str:
    cfg = json.loads((EXPERTS / name / ".codebuddy-plugin" / "plugin.json").read_text(encoding="utf-8"))
    c = CONTENT[name]
    zh, en = cfg["displayName"]["zh"], cfg["displayName"]["en"]
    avatar = Path(cfg["avatar"]).name
    assert (EXPERTS / name / cfg["avatar"]).exists(), f"头像断链: {name}"

    features = "\n".join(f"- **{k}**：{v}" for k, v in c["features"])
    examples = "\n".join(f"- {q['zh']}" for q in cfg["quickPrompts"])

    return "\n".join([
        f"# {zh}（{en}）",
        "",
        c["lead"],
        "",
        "## 类型",
        "",
        "Agent 型（单个 AI 专家）",
        "",
        "## 功能",
        "",
        features,
        "",
        f"交付物：{c['deliverables']}。",
        "",
        "## 工作方式",
        "",
        c["workflow"],
        "",
        "## 使用示例",
        "",
        examples,
        "",
        "## 头像",
        "",
        AVATAR_NOTE.format(avatar=avatar),
        "",
        "## 安装",
        "",
        "将整个专家包目录放到本机专家市场目录下：",
        "",
        "```",
        f"{MARKET}\\{name}\\",
        "```",
        "",
        "目录内应包含 `.codebuddy-plugin/plugin.json`、`agents/`、`avatars/` 和本 README。",
        "如需在市场清单中登记，在 `my-experts/.codebuddy-plugin/marketplace.json` 的 `plugins` 数组补一条",
        "`name` / `source` / `description` / `version`。完成后重启 WorkBuddy 让客户端重新扫描插件",
        "（头像与配置有缓存，不重启可能看不到更新）。",
        "",
        "## 打包分享",
        "",
        "在 `experts/` 目录下执行：",
        "",
        "```bash",
        f"zip -r {name}.zip {name}/",
        "```",
        "",
    ])


